def fail(msg):
    print("ERROR: " + msg)
    if len(sys.argv) < 2: input("Press Enter to exit...")
    sys.exit(1)

def main():
    src = sys.argv[1] if len(sys.argv) > 1 else input("Path to the XBlastOS 0.65 RAMTESTER .bin: ").strip().strip('"')
    if not os.path.isfile(src): fail("file not found: " + src)
    d = bytearray(open(src, "rb").read())
    if len(d) != 262144: fail("expected a 256 KB XBlast image, got %d bytes" % len(d))
    table = bytes(d[START:END])
    if table == NEW_TABLE: fail("this image is already patched for 1.4 - start from the original image")
    if hashlib.md5(table).hexdigest() != STOCK_TABLE_MD5:
        fail("start-up table does not match - not a stock XBlastOS 0.65 RAMTESTER image")
    d[START:END] = NEW_TABLE
    print("  0x0080-0x0FEF  start-up table replaced (1.4 transplant: force 1.6 path, Focus init, OEM chip RAM setup)")
    dst = sys.argv[2] if len(sys.argv) > 2 else os.path.join(
        os.path.dirname(os.path.abspath(src)), "XBlastOS_0.65_RAMTESTER_XGPUB_v1.4.bin")
    open(dst, "wb").write(d)
    print("\nSaved: " + dst)
    print("MD5:   " + hashlib.md5(d).hexdigest())
    print("Flash it to a spare bank. Press eject to start XBlast OS; its RAM tests are under Tools.")
    if len(sys.argv) < 2: input("Press Enter to exit...")

if __name__ == "__main__":
    main()
